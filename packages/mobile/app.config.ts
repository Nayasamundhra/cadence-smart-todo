import type { ConfigContext, ExpoConfig } from 'expo/config';
import { withSentry } from '@sentry/react-native/expo';

/**
 * Single place that defines the app's identity. The product name is not final:
 * renaming = change these env values (see .env.example), nothing else.
 * UI copy must read the name from `APP_NAME` in src/lib/appInfo.ts, never a literal.
 */
const APP_NAME = process.env.APP_NAME ?? 'Cadence';
const APP_SLUG = process.env.APP_SLUG ?? 'cadence';
const APP_SCHEME = process.env.APP_SCHEME ?? 'cadence';
// Placeholder. Must be replaced with the real identifier before the first store submission.
const APP_BUNDLE_ID = process.env.APP_BUNDLE_ID ?? 'com.example.cadence';

export default ({ config }: ConfigContext): ExpoConfig => {
  const base: ExpoConfig = {
    ...config,
    name: APP_NAME,
    slug: APP_SLUG,
    scheme: APP_SCHEME,
    version: '0.1.0',
    orientation: 'portrait',
    icon: './assets/icon.png',
    // Phase 1 (ThemeProvider) switches this to 'automatic'.
    userInterfaceStyle: 'light',
    ios: {
      supportsTablet: true,
      bundleIdentifier: APP_BUNDLE_ID,
    },
    android: {
      package: APP_BUNDLE_ID,
      adaptiveIcon: {
        backgroundColor: '#E6F4FE',
        foregroundImage: './assets/android-icon-foreground.png',
        backgroundImage: './assets/android-icon-background.png',
        monochromeImage: './assets/android-icon-monochrome.png',
      },
      predictiveBackGestureEnabled: false,
    },
    plugins: ['expo-router'],
    // typedRoutes is deliberately off: its types are generated by `expo start`, which would make
    // `tsc` in CI depend on a dev server run. Revisit when route count makes typos likely.
    // Expo account that owns the EAS project (created with `eas init`). Not a secret.
    owner: 'nayasa_mundhra24',
    extra: {
      appName: APP_NAME,
      eas: { projectId: '6f185a60-dfc8-41aa-8a4d-a98bb759f209' },
    },
  };

  // Source-map upload is only wired when an organisation and project are configured.
  // The upload itself additionally needs SENTRY_AUTH_TOKEN at build time (never committed).
  const sentryOrg = process.env.SENTRY_ORG;
  const sentryProject = process.env.SENTRY_PROJECT;
  if (sentryOrg && sentryProject) {
    return withSentry(base, {
      url: 'https://sentry.io/',
      organization: sentryOrg,
      project: sentryProject,
    });
  }
  return base;
};
